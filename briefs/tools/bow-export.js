/* BOW Review Auditor — spreadsheet output.
   One row model feeds the .xlsx, the CSV and the copy-to-Google-Sheets text,
   so all three always agree. Works in the browser (window.BowExport) and in Node. */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.BowExport = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  var HEADER = ['Component', 'Review Comment', 'Action/Advice', 'Recommended or Required Action', 'Link', 'Partner Comment', 'Reviewer Status', 'Date Modified'];
  var COLORS = { ink: 'FF1B2430', teal: 'FF257A70', tealSoft: 'FFE4F1EF', actionSoft: 'FFFBE9E1', actionInk: 'FF9A3A14', adviceInk: 'FF1D5F57', soft: 'FF4A5568', line: 'FFD5DAD7', paper: 'FFF2F4F1' };

  function pad(n) { return n < 10 ? '0' + n : '' + n; }
  function fmtDate(d) {
    var h = d.getHours(), ap = h >= 12 ? 'PM' : 'AM';
    h = h % 12; if (h === 0) h = 12;
    return pad(d.getMonth() + 1) + '/' + pad(d.getDate()) + '/' + pad(d.getFullYear() % 100) + ' ' + h + ':' + pad(d.getMinutes()) + ' ' + ap;
  }
  function stamp(d) { return d.getFullYear() + pad(d.getMonth() + 1) + pad(d.getDate()); }

  /* Row model for the main sheet. */
  function toRows(result, now) {
    now = now || new Date();
    var when = fmtDate(now), rows = [];
    rows.push({ kind: 'header', cells: HEADER.slice() });
    rows.push({ kind: 'section', cells: ['Build Checklist', '(checklist items to be considered & completed prior to build review)', '', '', '', '', '', when] });
    result.build.forEach(function (b) {
      rows.push({ kind: 'build', cells: [b.component, b.review, b.type, b.recommended, b.link, b.partnerComment, '', when] });
    });
    rows.push({ kind: 'blank', cells: ['', '', '', '', '', '', '', ''] });
    rows.push({ kind: 'section', cells: ['Review Feedback', "(Self-audit findings generated by the BOW Review Auditor from the uploaded export — not Workday's official review)", '', '', '', '', '', when] });
    result.findings.forEach(function (f) {
      rows.push({ kind: 'finding', type: f.type, cells: [f.component, f.comment, f.type, f.recommended, '', '', '', when] });
    });
    return rows;
  }

  function csvCell(v) { v = String(v == null ? '' : v); return /[",\r\n]/.test(v) ? '"' + v.replace(/"/g, '""') + '"' : v; }
  function toCSV(rows) { return '﻿' + rows.map(function (r) { return r.cells.map(csvCell).join(','); }).join('\r\n'); }

  /* Tab-separated, quoted where needed, for pasting straight into Google Sheets. */
  function tsvCell(v) {
    v = String(v == null ? '' : v);
    if (/^[=+\-@]/.test(v)) v = "'" + v;   // paste as text, never as a formula
    return /[\t\r\n"]/.test(v) ? '"' + v.replace(/"/g, '""') + '"' : v;
  }
  function toTSV(rows) { return rows.map(function (r) { return r.cells.map(tsvCell).join('\t'); }).join('\n'); }

  function sheetTitle(name) { return String(name || 'App').replace(/[\\\/\?\*\[\]:']/g, ' ').trim().slice(0, 22) + ' - Build Review'; }
  function fileStem(result) { return (result.app.referenceId || result.app.name || 'app').replace(/[^A-Za-z0-9_\-]/g, '_') + '_BOW_Review_' + stamp(new Date()); }

  function ruleResult(result, rule) {
    if (rule.manual) return 'Manual check';
    var c = result.byRule[rule.id];
    var n = c ? c.Action + c.Advice : 0;
    return n ? 'Findings (' + n + ')' : 'Pass';
  }

  function buildWorkbook(ExcelJS, result, opts) {
    opts = opts || {};
    var now = opts.now || new Date();
    var rows = toRows(result, now);
    var wb = new ExcelJS.Workbook();
    wb.creator = 'BOW Review Auditor';
    wb.created = now;

    var title = sheetTitle(result.app.name);
    var ws = wb.addWorksheet(title, { views: [{ state: 'frozen', ySplit: 1 }] });
    ws.columns = [{ width: 38 }, { width: 46 }, { width: 15 }, { width: 84 }, { width: 24 }, { width: 46 }, { width: 17 }, { width: 19 }];

    var font = { name: 'Arial', size: 10, color: { argb: COLORS.ink } };
    var thin = { style: 'thin', color: { argb: COLORS.line } };
    var border = { top: thin, left: thin, bottom: thin, right: thin };
    var firstFinding = 0, lastFinding = 0;

    rows.forEach(function (r, i) {
      var row = ws.addRow(r.cells);
      var rowNo = i + 1;
      row.eachCell({ includeEmpty: true }, function (cell, col) {
        cell.font = Object.assign({}, font);
        cell.alignment = { vertical: 'top', wrapText: true };
        if (r.kind !== 'blank') cell.border = border;
        if (r.kind === 'header') {
          cell.font = { name: 'Arial', size: 10, bold: true, color: { argb: 'FFFFFFFF' } };
          cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: COLORS.ink } };
          cell.alignment = { vertical: 'middle', wrapText: true };
        } else if (r.kind === 'section') {
          cell.font = { name: 'Arial', size: 10, bold: col <= 2, italic: col === 2, color: { argb: col === 1 ? COLORS.ink : COLORS.soft } };
          cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: COLORS.tealSoft } };
        } else if (r.kind === 'finding' && col === 3) {
          var act = r.type === 'Action';
          cell.font = { name: 'Arial', size: 10, bold: true, color: { argb: act ? COLORS.actionInk : COLORS.adviceInk } };
          cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: act ? COLORS.actionSoft : COLORS.tealSoft } };
          cell.alignment = { vertical: 'top', horizontal: 'center', wrapText: true };
        }
      });
      if (r.kind === 'header') row.height = 22;
      if (r.kind === 'finding') { if (!firstFinding) firstFinding = rowNo; lastFinding = rowNo; }
    });

    /* Comments tab: blank, like the Workday sheet (reviewers and partners add notes here). */
    var cm = wb.addWorksheet('Comments');
    cm.columns = [{ width: 38 }, { width: 70 }, { width: 22 }, { width: 19 }];
    var ch = cm.addRow(['Component', 'Comment', 'By', 'Date']);
    ch.eachCell(function (c) { c.font = { name: 'Arial', size: 10, bold: true, color: { argb: 'FFFFFFFF' } }; c.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: COLORS.ink } }; });

    /* Summary tab: same two counters as the Workday sheet, then a rule-by-rule result. */
    var sm = wb.addWorksheet('Summary');
    sm.columns = [{ width: 18 }, { width: 20 }, { width: 70 }, { width: 11 }, { width: 11 }, { width: 18 }];
    var q = "'" + title + "'";
    var a = sm.addRow(['# Action Items', lastFinding ? { formula: 'COUNTIF(' + q + '!C' + firstFinding + ':C' + lastFinding + ',"Action")', result: result.counts.Action } : 0]);
    var d = sm.addRow(['# Advice Items', lastFinding ? { formula: 'COUNTIF(' + q + '!C' + firstFinding + ':C' + lastFinding + ',"Advice")', result: result.counts.Advice } : 0]);
    [a, d].forEach(function (r) { r.getCell(1).font = { name: 'Arial', size: 10, bold: true, color: { argb: COLORS.ink } }; r.getCell(2).font = { name: 'Arial', size: 10, bold: true, color: { argb: COLORS.ink } }; r.getCell(2).alignment = { horizontal: 'left' }; });
    sm.addRow([]);
    sm.addRow(['App', result.app.name]).getCell(1).font = { name: 'Arial', size: 10, bold: true };
    sm.addRow(['App Ref ID', result.app.referenceId || '(no appManifest.json in the zip)']).getCell(1).font = { name: 'Arial', size: 10, bold: true };
    sm.addRow(['Files audited', result.fileCount]).getCell(1).font = { name: 'Arial', size: 10, bold: true };
    sm.addRow(['Generated', fmtDate(now)]).getCell(1).font = { name: 'Arial', size: 10, bold: true };
    sm.addRow([]);
    var rh = sm.addRow(['Rule', 'Area', 'Check', 'Action', 'Advice', 'Result']);
    rh.eachCell(function (c) { c.font = { name: 'Arial', size: 10, bold: true, color: { argb: 'FFFFFFFF' } }; c.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: COLORS.ink } }; });
    result.rules.forEach(function (rule) {
      var res = ruleResult(result, rule);
      if (rule.internal && res === 'Pass') return;
      var c = result.byRule[rule.id] || { Action: 0, Advice: 0 };
      var row = sm.addRow([rule.id, rule.area, rule.title, c.Action, c.Advice, res]);
      row.eachCell(function (cell) { cell.font = { name: 'Arial', size: 10, color: { argb: COLORS.ink } }; cell.alignment = { vertical: 'top', wrapText: true }; });
      var rc = row.getCell(6);
      rc.font = { name: 'Arial', size: 10, bold: true, color: { argb: res === 'Pass' ? 'FF256D4A' : res === 'Manual check' ? COLORS.soft : COLORS.actionInk } };
    });

    /* Detail tab: every individual occurrence behind the aggregated rows. */
    var dt = wb.addWorksheet('Details');
    dt.views = [{ state: 'frozen', ySplit: 1 }];
    dt.columns = [{ width: 7 }, { width: 18 }, { width: 11 }, { width: 38 }, { width: 44 }, { width: 34 }, { width: 8 }, { width: 90 }];
    var dh = dt.addRow(['Rule', 'Area', 'Type', 'Component', 'Review Comment', 'File', 'Line', 'Code']);
    dh.eachCell(function (c) { c.font = { name: 'Arial', size: 10, bold: true, color: { argb: 'FFFFFFFF' } }; c.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: COLORS.ink } }; });
    var areaOf = {};
    result.rules.forEach(function (r) { areaOf[r.id] = r.area; });
    result.details.forEach(function (x) {
      var row = dt.addRow([x.rule, areaOf[x.rule] || '', x.type, x.component, x.comment, x.file, x.line === '' ? '' : Number(x.line) || x.line, x.snippet]);
      row.eachCell(function (cell) { cell.font = { name: 'Arial', size: 9, color: { argb: COLORS.ink } }; cell.alignment = { vertical: 'top', wrapText: false }; });
      row.getCell(8).font = { name: 'Consolas', size: 9, color: { argb: COLORS.ink } };
    });
    dt.autoFilter = { from: { row: 1, column: 1 }, to: { row: Math.max(1, result.details.length + 1), column: 8 } };

    return wb;
  }

  return { HEADER: HEADER, toRows: toRows, toCSV: toCSV, toTSV: toTSV, buildWorkbook: buildWorkbook, fileStem: fileStem, sheetTitle: sheetTitle, fmtDate: fmtDate, ruleResult: ruleResult };
});
